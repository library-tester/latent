/* ── local helpers ────────────────────────────────────────────── */
const curse = id => { gainCard(mk(id)); };            // routed so Warding Slip can veto it
const anyCurse = () => curse(pick(['leak','rot']));
const row = () => (nodeAt(G.at) || { r:0 }).r;
const has = t => G.deck.filter(c => CARDS[c.id].t === t && CARDS[c.id].r !== 'curse').length;
/* Strip every curse out of the deck and report how many went. */
function purge(){
  const before = G.deck.length;
  G.deck = G.deck.filter(c => CARDS[c.id].r !== 'curse');
  return before - G.deck.length;
}

