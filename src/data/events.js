/* Room events — the prose, the options, and what each one costs you.

   `a` gates an event to a list of acts; an event without `a` is an archive
   fixture that can turn up in any of them. ui/rooms.js draws from the current
   act's slice without replacement, so a run works through fresh rooms before
   anything repeats.

   Two rules the options hold to:
     - `d` is a contract. If an option rolls for its outcome, the text says so.
     - Everything the player gains goes through the run-level helpers
       (gainCard, spendGold, raiseMaxHp…) rather than touching G directly, so
       relics that watch for curses, gold or cards actually see it happen. */

