/* Buff a specimen and say so over its head, in one line. */
const str = (e, n) => { e.str += n; fxOn(e.el, '+' + n + ' STR', 'lit'); };
const allStr = (e, n) => { if(!C) return;
  C.foes.filter(x => x.alive).forEach(x => { x.str += n; }); fxOn(e.el, '+' + n + ' STR ALL', 'lit'); };
const hits = (e, d, n) => { for(let i = 0; i < n; i++) eAtk(e, d); };

