/* The bestiary. Each entry carries its stats, its art key, its intent table and its AI.

   A move is `{ i, f }`: `i` is what the player is shown before it happens, `f`
   is what it does. `i` composes — any of damage (`d`, `x` times), block (`v`),
   `buff` and `deb`/`sdeb` may appear together, and each draws its own icon, so
   attack-and-block or block-and-debuff need no special case. Four values of
   `t` stand alone instead: 'sleep', 'stun', 'flee' and 'unknown'.

   `ai(e, t)` names next turn's move. Most are built from game/patterns.js
   rather than written out — `limit(2, weighted({...}))` is the Spire's real
   rule (roll by weight, never the same move three turns running) and is the
   default shape here. Hand-written ai() is for enemies whose behaviour is the
   point: the sealed ones that wake, the rat that runs off with your gold.

   An entry may also define `sawCard` / `sawAttack` / `sawSkill` / `sawPower`,
   which run when the player plays one — that is how a specimen punishes a
   whole category of card instead of only acting on its own turn. */

